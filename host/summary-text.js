'use strict';
/**
 * The text side of the "where are we" summary (backlog #39 job 1, documentation/DESIGN_SLAVE_MODE_SUMMARY.md).
 * Pure: no files, no network, no clock.
 *
 *   flattenTranscript(jsonlText, { maxChars, perMessage }) -> { messages, transcript, newestKey }
 *   buildPrompt(transcript)                                -> the whole prompt (transcript first, instruction last)
 *   cleanReply(raw)                                        -> 1 to 5 short plain lines, or null when the reply says nothing
 *   capMessage(text, cap)                                  -> text of at most `cap` UTF-16 units, start and end kept
 *
 * WHAT GOES IN (measured, 2026-10-03 serving report): only the person's and Claude's own words. The first draft
 * flattened everything that had `text` in it, and skill injections ("Base directory for this skill...") filled the
 * tails of two of three real sessions, so the model summarised a skill rather than the conversation. Dropped:
 * tool calls and results, thinking, sidechains (a subagent talking), `isMeta` messages, system-reminders (cut out of
 * a message, and a message that was only one disappears), command wrappers, local command output, task
 * notifications and interrupt markers.
 *
 * THE WINDOW is filled from the newest message backwards (the last few messages decide the summary), then put back
 * in chronological order. Each message is capped; a long one keeps its start AND its end, because an assistant's
 * conclusion lives at the end.
 *
 * `newestKey` is what "has anything new happened?" compares: the newest kept message's uuid, or a hash of its words
 * when the line has none. Tool-only growth of a transcript (a long agent run) leaves it unchanged, so it costs no job.
 *
 * Read-only by construction: nothing here touches a file. The person's words are never logged.
 */

const crypto = require('crypto');

const MAX_CHARS = 10_000;      // ~2.2k tokens: as good as 20k in the measurement, twice as fast
const PER_MESSAGE = 1_500;
const SEPARATOR = '\n\n';
const CUT = ' [...] ';
const LABEL = { user: 'User: ', assistant: 'Assistant: ' };

// An injected reminder is a block of its own: the tag opens a line and its closer ends one (Dexter F4, PR #105). A mention
// inside a sentence, a quoted pair or an unclosed tag is somebody's words and is kept whole.
const REMINDER_BLOCK = /(?:^|\n)[ \t]*<system-reminder>[\s\S]*?<\/system-reminder>[ \t]*(?=\n|$)/g;
// Claude Code appends the compaction summary as a user line (Dexter F2). Flagged `isCompactSummary` in real transcripts;
// the words are matched too, at the start of the message only, in case the flag is ever missing.
const COMPACT_SUMMARY = /^This session is being continued from a previous conversation/;
const NOT_CONVERSATION = /^(?:<command-(?:name|message|args)>|<local-command-|<task-notification>|<bash-(?:input|stdout|stderr)>|Base directory for this skill|\[Request interrupted|Caveat: The messages below were generated by the user)/;

const isObject = (o) => o !== null && typeof o === 'object' && !Array.isArray(o);

/** At most `cap` UTF-16 units, the start and the end kept, never a lone surrogate. */
function capMessage(text, cap) {
  if (typeof text !== 'string') return '';
  if (text.length <= cap) return text;
  const budget = cap - CUT.length;
  if (budget < 2) return text.slice(0, Math.max(0, cap));
  const headLen = Math.floor(budget * 0.6);
  const tailLen = budget - headLen;
  let head = text.slice(0, headLen);
  if (/[\uD800-\uDBFF]$/.test(head)) head = head.slice(0, -1);
  let tail = text.slice(text.length - tailLen);
  if (/^[\uDC00-\uDFFF]/.test(tail)) tail = tail.slice(1);
  return head + CUT + tail;
}

/** The words of one transcript line, or null when it is not a conversation message. */
function messageOf(obj) {
  if (!isObject(obj) || (obj.type !== 'user' && obj.type !== 'assistant')) return null;
  if (obj.isSidechain === true || obj.isMeta === true || obj.isCompactSummary === true) return null;
  const message = isObject(obj.message) ? obj.message : null;
  if (!message) return null;
  const c = message.content;
  let raw;
  if (typeof c === 'string') raw = c;
  else if (Array.isArray(c)) raw = c.filter(b => isObject(b) && b.type === 'text' && typeof b.text === 'string').map(b => b.text).join('\n');
  else return null;
  const text = raw.replace(REMINDER_BLOCK, '').trim();
  if (text === '' || NOT_CONVERSATION.test(text)) return null;
  if (obj.type === 'user' && COMPACT_SUMMARY.test(text)) return null;
  return { role: obj.type, text, uuid: typeof obj.uuid === 'string' && obj.uuid !== '' ? obj.uuid : null };
}

const keyOf = (m) => m.uuid !== null ? m.uuid : 'h:' + crypto.createHash('sha1').update(m.role + '\0' + m.text).digest('hex').slice(0, 16);

function flattenTranscript(jsonl, { maxChars = MAX_CHARS, perMessage = PER_MESSAGE } = {}) {
  const empty = { messages: [], transcript: '', newestKey: null };
  if (typeof jsonl !== 'string' || jsonl === '') return empty;
  const found = [];
  for (const l of jsonl.split(/\r?\n/)) {
    if (l.trim() === '') continue;
    let obj;
    try { obj = JSON.parse(l); } catch { continue; }
    const m = messageOf(obj);
    if (m) found.push(m);
  }
  const picked = [];
  let used = 0;
  for (let i = found.length - 1; i >= 0; i--) {
    const m = found[i];
    const text = capMessage(m.text, perMessage);
    const fits = LABEL[m.role].length + text.length + (picked.length ? SEPARATOR.length : 0);
    if (used + fits > maxChars) {
      if (picked.length > 0) break;
      const room = maxChars - LABEL[m.role].length;           // nothing kept yet: the newest message is cut to fit, not lost
      if (room < 20) break;
      picked.push({ role: m.role, text: capMessage(text, room), key: keyOf(m) });
      used = LABEL[m.role].length + picked[0].text.length;
      break;
    }
    used += fits;
    picked.push({ role: m.role, text, key: keyOf(m) });
  }
  if (picked.length === 0) return empty;
  picked.reverse();
  return {
    messages: picked,
    transcript: picked.map(m => LABEL[m.role] + m.text).join(SEPARATOR),
    newestKey: picked[picked.length - 1].key,
  };
}

// The instruction goes AFTER the transcript: put first, the model summarised the start (measured, stale summaries).
const INSTRUCTION = [
  '---',
  'Above is a conversation between a person (User) and an AI coding assistant (Assistant).',
  'In 3 to 5 short lines of plain text (no markdown, no bullets), say what they are working on, where it stands now, and what is next.',
  'Judge mainly by the last few messages. Use only what the conversation says; do not invent details.',
  'Use exactly this form:',
  'Working on: ...',
  'Where it stands: ...',
  'Next: ...',
].join('\n');

function buildPrompt(transcript) {
  return String(transcript == null ? '' : transcript) + '\n\n' + INSTRUCTION;
}

const LINE_MAX = 240;
const REPLY_MAX = 900;
const REPLY_LINES = 5;

// Controls (ESC included), bidi overrides and zero-width characters: a model fed web text can emit them, and the words
// reach a native tooltip (Miguel I3, PR #105). Tab and newline are not in the set.
const INVISIBLES = /[\u0000-\u0008\u000B-\u001F\u007F-\u009F\u200B-\u200F\u202A-\u202E\u2066-\u2069]/g;
// **bold** where it is bold: not inside a word, a path or a glob (src/**/*.js), and underscores are never touched
// because __init__.py is a name, not emphasis (Dexter F5).
const BOLD = /(?<![\w/*])\*\*(?=[^\s*])([^*\n]+?)(?<=[^\s*])\*\*(?![\w/*])/g;
const ONLY_MARKUP = /^[*_#`\-\s]*$/;

function stripMarkup(line) {
  let s = line.replace(INVISIBLES, '');
  for (let before = null; before !== s;) {          // removing one fence can join its neighbours into a new one
    before = s;
    s = s.replace(/```[a-z]*/gi, '');
  }
  s = s.replace(BOLD, '$1').trim();
  s = s.replace(/^(?:[-*•]|\d+[.)]|#{1,6})(?:\s+|$)/, '').trim();
  return ONLY_MARKUP.test(s) ? '' : s;
}

function clip(s, max) {
  if (s.length <= max) return s;
  let cut = s.slice(0, max - 1);
  if (/[\uD800-\uDBFF]$/.test(cut)) cut = cut.slice(0, -1);
  return cut.trimEnd() + '…';
}

/** The model's reply as 1 to 5 short plain lines, or null when it says nothing (never an empty summary). */
function cleanReply(raw) {
  if (typeof raw !== 'string') return null;
  const lines = [];
  for (const l of raw.split(/\r?\n/)) {
    const s = stripMarkup(l);
    if (s !== '') lines.push(clip(s, LINE_MAX));
    if (lines.length === REPLY_LINES) break;
  }
  if (lines.length === 0) return null;
  const out = clip(lines.join('\n'), REPLY_MAX).trimEnd();
  return out === '' ? null : out;
}

module.exports = { flattenTranscript, buildPrompt, cleanReply, capMessage, MAX_CHARS, PER_MESSAGE, INSTRUCTION };
